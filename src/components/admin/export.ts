"use client";

/**
 * Client-side export utilities.
 * CSV: generates a downloadable .csv file (opens natively in Excel).
 * PDF: triggers browser print dialog with print-specific styles (generates PDF via browser).
 * No third-party dependencies — sustainable (smaller bundle) and secure (no third-party code).
 */

/**
 * Export data as CSV (opens in Excel natively).
 * @param columns - Array of column headers
 * @param rows - Array of row objects
 * @param filename - Download filename
 */
export function exportToCsv(
  columns: string[],
  rows: Record<string, unknown>[],
  filename: string
): void {
  const header = columns.map((c) => `"${c.replace(/"/g, '""')}"`).join(",");
  const body = rows
    .map((row) =>
      columns
        .map((col) => {
          const val = row[col];
          const str = val === null || val === undefined ? "" : String(val);
          return `"${str.replace(/"/g, '""')}"`;
        })
        .join(",")
    )
    .join("\n");

  const csvContent = header + "\n" + body;
  const blob = new Blob([csvContent], { type: "text/csv;charset=utf-8;" });
  const url = URL.createObjectURL(blob);
  const link = document.createElement("a");
  link.setAttribute("href", url);
  link.setAttribute("download", `${filename}.csv`);
  link.style.visibility = "hidden";
  document.body.appendChild(link);
  link.click();
  document.body.removeChild(link);
  URL.revokeObjectURL(url);
}

/**
 * Export campaign data as CSV.
 */
export function exportCampaignsToCsv(
  campaigns: Array<{
    id: string;
    name: string;
    brandName: string;
    influencerName: string;
    status: string;
    budget: number;
    currency: string;
    startDate: string;
    endDate?: string;
    createdAt: string;
  }>,
  filename: string = "campaigns"
): void {
  exportToCsv(
    [
      "ID",
      "Campaign Name",
      "Brand",
      "Influencer",
      "Status",
      "Budget",
      "Currency",
      "Start Date",
      "End Date",
      "Created At",
    ],
    campaigns.map((c) => ({
      ID: c.id,
      "Campaign Name": c.name,
      Brand: c.brandName,
      Influencer: c.influencerName,
      Status: c.status,
      Budget: c.budget,
      Currency: c.currency,
      "Start Date": c.startDate,
      "End Date": c.endDate || "",
      "Created At": c.createdAt,
    })),
    filename
  );
}

/**
 * Trigger browser print dialog for PDF generation.
 * @param elementId - ID of the element to print
 * @param title - Document title for the PDF
 */
export function exportToPdf(elementId: string, title: string): void {
  const element = document.getElementById(elementId);
  if (!element) {
    console.error(`Element #${elementId} not found for PDF export`);
    return;
  }

  const originalContent = document.body.innerHTML;
  const printContent = element.outerHTML;
  const printStyles = `
    <style>
      @page { size: A4; margin: 1cm; }
      body { font-family: system-ui, -apple-system, sans-serif; font-size: 11px; color: #111; }
      .no-print { display: none !important; }
      .print-header { text-align: center; margin-bottom: 2rem; }
      .print-title { font-size: 24px; font-weight: 700; margin-bottom: 0.5rem; }
      .print-subtitle { color: #666; font-size: 12px; }
      table { width: 100%; border-collapse: collapse; margin-bottom: 1rem; }
      th, td { border: 1px solid #ddd; padding: 6px 8px; text-align: left; font-size: 11px; }
      th { background: #f4f4f5; font-weight: 600; }
      .print-footer { margin-top: 2rem; border-top: 1px solid #ddd; padding-top: 1rem; font-size: 9px; color: #666; }
    </style>
  `;

  document.body.innerHTML = `
    <div class="no-print">
      ${printStyles}
      <div class="print-header">
        <div class="print-title">${escapeHtml(title)}</div>
        <div class="print-subtitle">Generated by CALLBACX MARKETING — Admin Reports</div>
        <div class="print-subtitle">${new Date().toLocaleDateString()}</div>
      </div>
      ${printContent}
      <div class="print-footer">
        CALLBACX MARKETING — Confidential. This report contains campaign data and is intended for internal use only.
      </div>
    </div>
  `;

  window.print();

  document.body.innerHTML = originalContent;
}

/**
 * Escape HTML for safe display in print context.
 */
function escapeHtml(unsafe: string): string {
  return unsafe
    .replace(/&/g, "&amp;")
    .replace(/</g, "&lt;")
    .replace(/>/g, "&gt;")
    .replace(/"/g, "&quot;")
    .replace(/'/g, "&#039;");
}

/**
 * Download JSON data as a file (for data analyst use).
 */
export function exportToJson(
  data: unknown,
  filename: string
): void {
  const json = JSON.stringify(data, null, 2);
  const blob = new Blob([json], { type: "application/json;charset=utf-8;" });
  const url = URL.createObjectURL(blob);
  const link = document.createElement("a");
  link.setAttribute("href", url);
  link.setAttribute("download", `${filename}.json`);
  link.style.visibility = "hidden";
  document.body.appendChild(link);
  link.click();
  document.body.removeChild(link);
  URL.revokeObjectURL(url);
}
